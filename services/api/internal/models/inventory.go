package models

import (
	"time"

	"github.com/google/uuid"
)

// InventoryStock is the denormalized current balance for one (grade, pack
// size) combination. Updated atomically alongside every InventoryTransaction
// insert — the dashboard reads this table directly instead of SUM()-ing the
// full ledger on every request.
type InventoryStock struct {
	ProductID     uint      `json:"productId" gorm:"primaryKey"`
	Product       Product   `json:"product" gorm:"foreignKey:ProductID;constraint:OnUpdate:CASCADE,OnDelete:RESTRICT"`
	SizeInLiters  float64   `json:"sizeInLiters" gorm:"primaryKey;type:numeric(8,2)"`
	QuantityUnits int       `json:"quantityUnits" gorm:"not null;default:0;check:quantity_units >= 0"`
	UpdatedAt     time.Time `json:"updatedAt"`
}

type InventoryTxnType string

const (
	InventoryTxnInward  InventoryTxnType = "inward"
	InventoryTxnOutward InventoryTxnType = "outward"
)

// InventoryTransaction is the append-only stock ledger. Every inward entry
// (a staff member receiving fresh drums) and every stock-affecting outward
// movement (an order reaching Dispatched — see OrderHandler.UpdateStatus)
// writes one row here. Rows are never updated except by an admin correcting
// a mistaken entry (InventoryHandler.UpdateTransaction) — everyone else only
// ever appends.
type InventoryTransaction struct {
	Base
	ProductID     uint             `json:"productId" gorm:"not null;index:idx_txn_grade_size,priority:1"`
	Product       Product          `json:"product" gorm:"foreignKey:ProductID;constraint:OnUpdate:CASCADE,OnDelete:RESTRICT"`
	SizeInLiters  float64          `json:"sizeInLiters" gorm:"not null;type:numeric(8,2);index:idx_txn_grade_size,priority:2"`
	TxnType       InventoryTxnType `json:"txnType" gorm:"type:varchar(10);not null;check:txn_type IN ('inward','outward')"`
	QuantityUnits int              `json:"quantityUnits" gorm:"not null;check:quantity_units > 0"`
	EntryDate     time.Time        `json:"entryDate" gorm:"type:date;not null"`
	EnteredByID   uint             `json:"enteredById" gorm:"not null;index"`
	EnteredBy     User             `json:"enteredBy" gorm:"foreignKey:EnteredByID;constraint:OnUpdate:CASCADE,OnDelete:RESTRICT"`
	OrderID       *uint            `json:"orderId" gorm:"index"` // set only for 'outward' rows generated by a dispatch
	Order         *Order           `json:"order,omitempty" gorm:"foreignKey:OrderID;constraint:OnUpdate:CASCADE,OnDelete:SET NULL"`

	// Idempotency key. Client-generated (UUID v4) at the moment an inward
	// entry is created — including offline, before it's ever synced — and
	// resent unchanged on every retry. The unique constraint is what makes
	// InventoryHandler.SyncInward safe to replay: a duplicate insert attempt
	// with the same ClientTxnID is rejected at the DB level, not re-applied.
	ClientTxnID uuid.UUID `json:"clientTxnId" gorm:"type:uuid;uniqueIndex;not null"`
}
